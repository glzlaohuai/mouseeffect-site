import sharp from "sharp";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createHash } from "node:crypto";
const source = process.argv[2];
if (!source)
  throw new Error(
    "Usage: node scripts/import-screenshots.mjs /absolute/path/to/current/raw/screenshots",
  );
const names = ["library", "editor", "settings", "purchase"];
// Read all four before writing so an incomplete capture set cannot silently ship.
const originals = await Promise.all(
  names.map((name) => readFile(join(source, `${name}.png`))),
);
await mkdir("src/generated", { recursive: true });
const sizes = {};
const provenance = [];
for (let i = 0; i < names.length; i++) {
  const name = names[i],
    original = originals[i];
  const image = sharp(original);
  const meta = await image.metadata();
  if (!meta.width || !meta.height || meta.width < 500 || meta.height < 300)
    throw new Error(`Invalid screenshot: ${name}`);
  const info = await image
    .resize({ width: 1440, withoutEnlargement: true })
    .webp({ quality: 88, effort: 6 })
    .toFile(`public/images/${name}.webp`);
  sizes[name] = { width: info.width, height: info.height };
  provenance.push({
    file: `${name}.png`,
    sha256: createHash("sha256").update(original).digest("hex"),
    originalSize: { width: meta.width, height: meta.height },
    output: `${name}.webp`,
    outputBytes: info.size,
  });
}
await writeFile(
  "src/generated/screenshots.ts",
  `// Generated by scripts/import-screenshots.mjs from current app captures.\nexport const screenshots = ${JSON.stringify(sizes, null, 2)} as const;\n`,
);
await writeFile("SCREENSHOTS.json", JSON.stringify(provenance, null, 2) + "\n");
console.log(JSON.stringify(provenance, null, 2));
